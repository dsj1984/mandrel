// lib/cli/__tests__/registry-codex.test.js
/**
 * The Codex doctor checks (Story #5655): `codex-skills-in-sync` and
 * `codex-agents-in-sync` mirror `commands-in-sync` / `agents-in-sync`, and
 * `codex-instructions` sizes AGENTS.md against `project_doc_max_bytes`.
 */

import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, describe, it } from 'node:test';

import {
  SYSTEM_PROMPT_BLOCK,
  SYSTEM_PROMPT_ENTRY_DOC,
} from '../../../.agents/scripts/lib/bootstrap/agents-md-fold.js';
import { syncCodexAgents } from '../../../.agents/scripts/lib/codex/agents-projection.js';
import { syncCodexSkills } from '../../../.agents/scripts/lib/codex/skills-projection.js';
import { makeTempDir } from '../../../.agents/scripts/lib/test-temp.js';
import {
  CODEX_PROJECT_DOC_MAX_BYTES,
  readProjectDocMaxBytes,
  registry,
} from '../registry.js';

const check = (name) => registry.find((c) => c.name === name);

let root;

function write(rel, body) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body, 'utf8');
}

beforeEach(() => {
  root = makeTempDir('registry-codex-');
  write('.agents/workflows/alpha.md', '---\ndescription: Alpha flow.\n---\n');
  write('.agents/workflows/beta.md', '---\ndescription: Beta flow.\n---\n');
  write(
    '.agents/agents/story-worker.md',
    '---\nname: story-worker\ndescription: Worker.\n---\n\nBody.\n',
  );
});

afterEach(() => {
  fs.rmSync(root, { recursive: true, force: true });
});

describe('codex-skills-in-sync', () => {
  const run = () => check('codex-skills-in-sync').run({ projectRoot: root });

  it('passes once the projection is written', () => {
    syncCodexSkills({ projectRoot: root });
    const result = run();
    assert.equal(result.ok, true, result.detail);
    assert.match(result.detail, /2 Codex skills up to date/);
  });

  it('fails with the sync-commands remedy when the projection is missing', () => {
    const result = run();
    assert.equal(result.ok, false);
    assert.match(result.detail, /2 not synced/);
    assert.match(result.remedy, /mandrel sync-commands/);
  });

  it('fails as stale when a skill was hand-edited or its workflow removed', () => {
    syncCodexSkills({ projectRoot: root });
    write(
      '.agents/skills/workflows/alpha/SKILL.md',
      `<!-- AUTO-GENERATED by mandrel edited -->\n`,
    );
    fs.rmSync(path.join(root, '.agents', 'workflows', 'beta.md'));
    const result = run();
    assert.equal(result.ok, false);
    assert.match(result.detail, /2 stale/);
    assert.match(result.remedy, /mandrel sync-commands/);
  });
});

describe('codex-agents-in-sync', () => {
  const run = () => check('codex-agents-in-sync').run({ projectRoot: root });

  it('passes once the projection is written', () => {
    syncCodexAgents({ projectRoot: root });
    assert.equal(run().ok, true);
  });

  it('fails with the sync-agents remedy when missing or stale', () => {
    const missing = run();
    assert.equal(missing.ok, false);
    assert.match(missing.detail, /1 not synced/);
    assert.match(missing.remedy, /mandrel sync-agents/);
    syncCodexAgents({ projectRoot: root });
    write(
      '.agents/agents/story-worker.md',
      '---\ndescription: Changed.\n---\n',
    );
    const stale = run();
    assert.equal(stale.ok, false);
    assert.match(stale.detail, /1 stale/);
  });
});

describe('codex-instructions', () => {
  const PROJECT = path.join(path.sep, 'consumer');
  const HOME = path.join(path.sep, 'home', 'op');

  function run(files, env = {}) {
    return check('codex-instructions').run({
      projectRoot: PROJECT,
      env,
      homeDir: HOME,
      readText: (file) => files[file] ?? null,
    });
  }

  const agentsMd = (body) => ({ [path.join(PROJECT, 'AGENTS.md')]: body });

  it('passes a top-placed block within the default limit', () => {
    const result = run(agentsMd(`# P\n\n${SYSTEM_PROMPT_BLOCK}\nnotes\n`));
    assert.equal(result.ok, true);
    assert.match(
      result.detail,
      /within project_doc_max_bytes 32768 \(the Codex default\)/,
    );
  });

  it('fails when the block starts beyond the limit', () => {
    const body = `# P\n\n${'x'.repeat(CODEX_PROJECT_DOC_MAX_BYTES)}\n\n${SYSTEM_PROMPT_BLOCK}`;
    const result = run(agentsMd(body));
    assert.equal(result.ok, false);
    assert.match(result.detail, /beyond project_doc_max_bytes 32768/);
    assert.match(result.remedy, /top of the file|mandrel update/);
  });

  it('passes with an advisory naming byte counts when only the tail is cut', () => {
    const body = `# P\n\n${SYSTEM_PROMPT_BLOCK}\n${'y'.repeat(40000)}\n`;
    const result = run(agentsMd(body));
    assert.equal(result.ok, true);
    assert.match(
      result.detail,
      new RegExp(`is ${Buffer.byteLength(body)} bytes, over`),
    );
    assert.match(result.detail, /project_doc_max_bytes/);
  });

  it('reads the project .codex/config.toml limit first', () => {
    const files = {
      ...agentsMd(`# P\n\n${'z'.repeat(200)}\n\n${SYSTEM_PROMPT_BLOCK}`),
      [path.join(PROJECT, '.codex', 'config.toml')]:
        'project_doc_max_bytes = 100\n',
      [path.join(HOME, '.codex', 'config.toml')]:
        'project_doc_max_bytes = 99999\n',
    };
    const result = run(files);
    assert.equal(result.ok, false);
    assert.match(result.detail, /100 \(\.codex\/config\.toml\)/);
  });

  it('falls back to $CODEX_HOME, then ~/.codex', () => {
    const body = agentsMd(SYSTEM_PROMPT_ENTRY_DOC);
    const viaHome = run({
      ...body,
      [path.join(HOME, '.codex', 'config.toml')]:
        'project_doc_max_bytes = 50000\n',
    });
    assert.match(viaHome.detail, /50000 \(\$CODEX_HOME\/config\.toml\)/);
    const codexHome = path.join(path.sep, 'opt', 'codex');
    const viaEnv = run(
      {
        ...body,
        [path.join(codexHome, 'config.toml')]:
          'project_doc_max_bytes = 60000\n',
      },
      { CODEX_HOME: codexHome },
    );
    assert.match(viaEnv.detail, /60000/);
  });

  it('sizes AGENTS.override.md in preference to AGENTS.md', () => {
    const result = run({
      ...agentsMd(SYSTEM_PROMPT_ENTRY_DOC),
      [path.join(PROJECT, 'AGENTS.override.md')]: '# Override\n',
    });
    assert.equal(result.ok, false);
    assert.match(
      result.detail,
      /AGENTS\.override\.md carries no Mandrel read directive/,
    );
  });

  it('fails when AGENTS.md is absent or carries only the legacy import', () => {
    assert.equal(run({}).ok, false);
    const legacy = run(
      agentsMd('# P\n\n## System Prompt\n\n@.agents/instructions.md\n'),
    );
    assert.equal(legacy.ok, false);
    assert.match(legacy.remedy, /mandrel update/);
  });
});

describe('readProjectDocMaxBytes', () => {
  it('reads only a top-level integer line before any table header', () => {
    assert.equal(
      readProjectDocMaxBytes('project_doc_max_bytes = 4096\n'),
      4096,
    );
    assert.equal(
      readProjectDocMaxBytes('model = "x"\nproject_doc_max_bytes=12 # note\n'),
      12,
    );
    assert.equal(
      readProjectDocMaxBytes('[profile]\nproject_doc_max_bytes = 5\n'),
      null,
    );
    assert.equal(readProjectDocMaxBytes('project_doc_max_bytes = "5"\n'), null);
    assert.equal(readProjectDocMaxBytes(null), null);
  });
});
