/**
 * Codex skill projection of the workflow set: one
 * `.agents/skills/workflows/<name>/SKILL.md` per projectable workflow, from the
 * same source set and exclusions as the Claude command projection. Each skill
 * is a pointer to its workflow file, never a copy. Node built-ins only, so
 * the doctor registry can import it before third-party packages exist.
 *
 * @module codex/skills-projection
 */

import fs from 'node:fs';
import path from 'node:path';

import { isCommandExcluded } from '../command-header.js';
import { extractDescription } from '../mandrel-catalog.js';
import {
  collectLocalSkillFiles,
  collectSkillFiles,
} from '../skills/walk-skill-files.js';

/**
 * Project-relative POSIX home of the projection. Outside the `core`/`stack`
 * tiers, so the skills index never walks it; not dot-prefixed, because Codex
 * skips hidden directories when it scans `.agents/skills/`.
 */
export const CODEX_SKILLS_DIR = '.agents/skills/workflows';

/** Codex's skill-metadata limits. */
const CODEX_SKILL_NAME_MAX = 64;
const CODEX_SKILL_DESCRIPTION_MAX = 1024;

/** Every generated SKILL.md carries this; the reap touches nothing without it. */
const CODEX_SKILL_MARKER = '<!-- AUTO-GENERATED by mandrel';

const LOOPS_NS = 'loops';

/**
 * @param {string} dir
 * @returns {boolean}
 */
function dirExists(dir) {
  try {
    return fs.statSync(dir).isDirectory();
  } catch {
    return false;
  }
}

/**
 * @param {string} dir
 * @param {(entry: import('node:fs').Dirent) => boolean} keep
 * @returns {string[]}
 */
function mdFilesIn(dir, keep) {
  if (!dirExists(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.md') && keep(e))
    .map((e) => e.name)
    .sort();
}

/**
 * The workflows both projections expose: top-level `*.md` plus `loops/*.md`
 * (minus its README) from the payload, then the local zone. The payload wins
 * a collision; a `command: false` workflow is skipped.
 *
 * @param {{ payloadSrc: string, localSrc: string }} sources
 * @returns {Array<{ name: string, sourcePath: string, content: string }>}
 */
function listProjectableWorkflows({ payloadSrc, localSrc }) {
  const byName = new Map();
  for (const dir of [payloadSrc, localSrc]) {
    const candidates = [
      ...mdFilesIn(dir, () => true).map((f) => ({
        name: f.replace(/\.md$/, ''),
        sourcePath: path.join(dir, f),
      })),
      ...mdFilesIn(
        path.join(dir, LOOPS_NS),
        (e) => e.name.toLowerCase() !== 'readme.md',
      ).map((f) => ({
        name: `${LOOPS_NS}-${f.replace(/\.md$/, '')}`,
        sourcePath: path.join(dir, LOOPS_NS, f),
      })),
    ];
    for (const candidate of candidates) {
      if (byName.has(candidate.name)) continue;
      const content = fs.readFileSync(candidate.sourcePath, 'utf8');
      if (isCommandExcluded(content)) continue;
      byName.set(candidate.name, { ...candidate, content });
    }
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * @param {string} projectRoot
 * @param {string} absPath
 * @returns {string}
 */
function toPosixRelative(projectRoot, absPath) {
  return path.relative(projectRoot, absPath).split(path.sep).join('/');
}

/**
 * @param {string | null} description
 * @param {string} name
 * @returns {string}
 */
function skillDescription(description, name) {
  const text = description ?? `Run the Mandrel ${name} workflow.`;
  return text.length > CODEX_SKILL_DESCRIPTION_MAX
    ? `${text.slice(0, CODEX_SKILL_DESCRIPTION_MAX - 1)}…`
    : text;
}

/**
 * The SKILL.md for one workflow. `description` is a JSON string, which is
 * also a valid YAML double-quoted scalar whatever the workflow text holds.
 *
 * @param {{ name: string, description: string | null, workflowPath: string }} input
 *   `workflowPath` is project-relative POSIX.
 * @returns {string}
 */
function renderCodexSkill({ name, description, workflowPath }) {
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(skillDescription(description, name))}`,
    '---',
    '',
    `${CODEX_SKILL_MARKER} from ${workflowPath} — do not edit. Re-run: npm run sync:commands -->`,
    '',
    `# $${name}`,
    '',
    `Read \`${workflowPath}\` in full and execute it as the workflow for this`,
    `request. Treat the text that follows \`$${name}\` in the request as the`,
    "workflow's ARGUMENTS.",
    '',
  ].join('\n');
}

/**
 * Every projected skill keyed by name, with the exact SKILL.md it should hold.
 * Throws on a name Codex cannot load or that collides with an authored skill.
 *
 * @param {{ projectRoot: string, payloadSrc?: string, localSrc?: string }} opts
 * @returns {Map<string, string>}
 */
export function expectedCodexSkills({
  projectRoot,
  payloadSrc = path.join(projectRoot, '.agents', 'workflows'),
  localSrc = path.join(projectRoot, '.agents', 'local', 'workflows'),
}) {
  const expected = new Map();
  for (const wf of listProjectableWorkflows({ payloadSrc, localSrc })) {
    expected.set(
      wf.name,
      renderCodexSkill({
        name: wf.name,
        description: extractDescription(wf.content),
        workflowPath: toPosixRelative(projectRoot, wf.sourcePath),
      }),
    );
  }
  assertProjectableNames(projectRoot, expected.keys());
  return expected;
}

/**
 * `name:` of a SKILL.md's front-matter, or null.
 *
 * @param {string} file
 * @returns {string | null}
 */
function skillNameOf(file) {
  try {
    const source = fs.readFileSync(file, 'utf8');
    const fm = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    return fm?.[1].match(/^name:\s*["']?([^"'\s]+)/m)?.[1] ?? null;
  } catch {
    return null;
  }
}

/**
 * Fails loudly on a projected name Codex cannot load or that would collide
 * with a hand-authored payload or local skill.
 *
 * @param {string} projectRoot
 * @param {Iterable<string>} names
 */
function assertProjectableNames(projectRoot, names) {
  const taken = new Map();
  for (const file of [
    ...collectSkillFiles(projectRoot),
    ...collectLocalSkillFiles(projectRoot),
  ]) {
    const skillName = skillNameOf(file);
    if (skillName) taken.set(skillName, toPosixRelative(projectRoot, file));
  }
  for (const name of names) {
    if (name.length > CODEX_SKILL_NAME_MAX) {
      throw new Error(
        `codex skill projection: workflow name '${name}' exceeds Codex's ${CODEX_SKILL_NAME_MAX}-character skill-name limit.`,
      );
    }
    if (taken.has(name)) {
      throw new Error(
        `codex skill projection: workflow '${name}' collides with the skill of the same name at ${taken.get(name)} — rename one of them.`,
      );
    }
  }
}

/**
 * Generated skill directories currently on disk (marker-bearing only).
 *
 * @param {string} destDir
 * @returns {string[]}
 */
export function listGeneratedCodexSkills(destDir) {
  if (!dirExists(destDir)) return [];
  return fs
    .readdirSync(destDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .filter((name) => {
      try {
        return fs
          .readFileSync(path.join(destDir, name, 'SKILL.md'), 'utf8')
          .includes(CODEX_SKILL_MARKER);
      } catch {
        return false;
      }
    })
    .sort();
}

/**
 * Write the projection, reap marker-bearing orphans, skip unchanged files.
 *
 * @param {{
 *   projectRoot: string,
 *   payloadSrc?: string,
 *   localSrc?: string,
 *   destDir?: string,
 *   log?: (line: string) => void,
 * }} opts
 * @returns {{ written: string[], removed: string[], total: number }}
 */
export function syncCodexSkills({
  projectRoot,
  payloadSrc,
  localSrc,
  destDir = path.join(projectRoot, ...CODEX_SKILLS_DIR.split('/')),
  log = () => {},
}) {
  const expected = expectedCodexSkills({ projectRoot, payloadSrc, localSrc });

  const removed = [];
  for (const name of listGeneratedCodexSkills(destDir)) {
    if (expected.has(name)) continue;
    fs.rmSync(path.join(destDir, name), { recursive: true, force: true });
    removed.push(name);
    log(`  removed  ${CODEX_SKILLS_DIR}/${name} (no longer in workflows)`);
  }

  const written = [];
  for (const [name, body] of expected) {
    const file = path.join(destDir, name, 'SKILL.md');
    let current = null;
    try {
      current = fs.readFileSync(file, 'utf8');
    } catch {
      // absent — written below
    }
    if (current === body) continue;
    if (current !== null && !current.includes(CODEX_SKILL_MARKER)) {
      throw new Error(
        `codex skill projection: ${CODEX_SKILLS_DIR}/${name}/SKILL.md is hand-authored — move it out of the generated directory.`,
      );
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, body, 'utf8');
    written.push(name);
    log(`  synced   ${CODEX_SKILLS_DIR}/${name}`);
  }
  return { written, removed, total: expected.size };
}
