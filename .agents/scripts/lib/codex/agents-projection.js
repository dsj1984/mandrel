/**
 * Codex custom-agent projection of the role set: each `.agents/agents/<role>.md`
 * (payload, then `.agents/local/agents/`) becomes
 * `.codex/agents/mandrel-<role>.toml`. Codex resolves no `@` imports, so an
 * import line is inlined here; no `model` is ever emitted, because
 * `delivery.routing.agentModels` values are Claude-only. Node built-ins only,
 * so the doctor registry can import it.
 *
 * @module codex/agents-projection
 */

import fs from 'node:fs';
import path from 'node:path';

import { extractDescription } from '../mandrel-catalog.js';

/** Project-relative POSIX home of the projection. */
export const CODEX_AGENTS_DIR = '.codex/agents';

/** Generated files are `mandrel-<role>.toml`; consumer agents are never named so. */
const CODEX_AGENT_PREFIX = 'mandrel-';

/** First line of every generated file; the reap touches nothing without it. */
const CODEX_AGENT_HEADER = '# AUTO-GENERATED by mandrel';

const FRONTMATTER_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;
const IMPORT_LINE_RE = /^@(\S+)\s*$/;

/**
 * @param {string} dir
 * @returns {string[]}
 */
function roleFilesIn(dir) {
  try {
    return fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith('.md'))
      .map((e) => e.name)
      .sort();
  } catch {
    return [];
  }
}

/**
 * Role files from both sources; the payload wins a collision.
 *
 * @param {{ payloadSrc: string, localSrc: string }} sources
 * @returns {Array<{ role: string, sourcePath: string }>}
 */
function listRoleSources({ payloadSrc, localSrc }) {
  const byRole = new Map();
  for (const dir of [payloadSrc, localSrc]) {
    for (const file of roleFilesIn(dir)) {
      const role = file.replace(/\.md$/, '');
      if (!byRole.has(role)) {
        byRole.set(role, { role, sourcePath: path.join(dir, file) });
      }
    }
  }
  return [...byRole.values()].sort((a, b) => a.role.localeCompare(b.role));
}

/** Short escapes TOML basic strings accept. */
const TOML_SHORT_ESCAPES = Object.freeze({
  '\\': '\\\\',
  '"': '\\"',
  '\n': '\\n',
  '\t': '\\t',
  '\r': '\\r',
});

/**
 * Control characters (U+0000–U+001F, U+007F), which TOML forbids raw.
 *
 * @param {string} ch
 * @returns {boolean}
 */
function isControl(ch) {
  const code = ch.charCodeAt(0);
  return code < 0x20 || code === 0x7f;
}

/**
 * @param {string} ch
 * @returns {string}
 */
function unicodeEscape(ch) {
  return `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`;
}

/**
 * A TOML basic string (single line), escaping what the spec forbids raw.
 *
 * @param {string} value
 * @returns {string}
 */
function tomlString(value) {
  let out = '';
  for (const ch of String(value)) {
    if (TOML_SHORT_ESCAPES[ch]) out += TOML_SHORT_ESCAPES[ch];
    else out += isControl(ch) ? unicodeEscape(ch) : ch;
  }
  return `"${out}"`;
}

/**
 * A TOML multi-line basic string. Newlines and tabs stay raw; a `"""` run is
 * broken so it cannot close the string early.
 *
 * @param {string} value
 * @returns {string}
 */
function tomlMultiline(value) {
  let body = '';
  for (const ch of String(value).replace(/\r\n/g, '\n')) {
    if (ch === '\\') body += '\\\\';
    else if (ch === '\n' || ch === '\t' || !isControl(ch)) body += ch;
    else body += unicodeEscape(ch);
  }
  body = body.replace(/"""/g, '""\\"');
  return `"""\n${body.endsWith('\n') ? body : `${body}\n`}"""`;
}

/**
 * Replace each whole-line `@<path>` import with the imported file's text,
 * resolved against the role file's directory. A missing target throws.
 *
 * @param {string} body
 * @param {string} baseDir
 * @returns {string}
 */
function inlineImports(body, baseDir) {
  return body
    .split('\n')
    .map((line) => {
      const match = IMPORT_LINE_RE.exec(line);
      if (!match) return line;
      const target = path.resolve(baseDir, match[1]);
      try {
        return fs.readFileSync(target, 'utf8').replace(/\n+$/, '');
      } catch {
        throw new Error(
          `codex agent projection: cannot inline '${line.trim()}' from ${baseDir} — ${target} is unreadable.`,
        );
      }
    })
    .join('\n');
}

/**
 * The `.toml` for one role.
 *
 * @param {{ role: string, source: string, baseDir: string, sourceLabel: string }} input
 * @returns {string}
 */
function renderCodexAgent({ role, source, baseDir, sourceLabel }) {
  const fm = FRONTMATTER_RE.exec(source);
  const body = fm ? source.slice(fm[0].length) : source;
  const description =
    extractDescription(source) ?? `Mandrel ${role} role agent.`;
  const effort = fm?.[1].match(/^effort:\s*["']?([\w-]+)/m)?.[1] ?? null;
  const lines = [
    `${CODEX_AGENT_HEADER} from ${sourceLabel} — do not edit. Re-run: npm run sync:agents`,
    `name = ${tomlString(role)}`,
    `description = ${tomlString(description)}`,
  ];
  if (effort) lines.push(`model_reasoning_effort = ${tomlString(effort)}`);
  lines.push(
    `developer_instructions = ${tomlMultiline(inlineImports(body.replace(/^\n+/, ''), baseDir))}`,
  );
  return `${lines.join('\n')}\n`;
}

/**
 * Every projected agent keyed by its `.toml` file name.
 *
 * @param {{ projectRoot: string, payloadSrc?: string, localSrc?: string }} opts
 * @returns {Map<string, string>}
 */
export function expectedCodexAgents({
  projectRoot,
  payloadSrc = path.join(projectRoot, '.agents', 'agents'),
  localSrc = path.join(projectRoot, '.agents', 'local', 'agents'),
}) {
  const expected = new Map();
  for (const { role, sourcePath } of listRoleSources({
    payloadSrc,
    localSrc,
  })) {
    expected.set(
      `${CODEX_AGENT_PREFIX}${role}.toml`,
      renderCodexAgent({
        role,
        source: fs.readFileSync(sourcePath, 'utf8'),
        baseDir: path.dirname(sourcePath),
        sourceLabel: path
          .relative(projectRoot, sourcePath)
          .split(path.sep)
          .join('/'),
      }),
    );
  }
  return expected;
}

/**
 * Generated agent files on disk: `mandrel-*.toml` opening with the header.
 *
 * @param {string} destDir
 * @returns {string[]}
 */
export function listGeneratedCodexAgents(destDir) {
  let names;
  try {
    names = fs.readdirSync(destDir);
  } catch {
    return [];
  }
  return names
    .filter((f) => f.startsWith(CODEX_AGENT_PREFIX) && f.endsWith('.toml'))
    .filter((f) => {
      try {
        return fs
          .readFileSync(path.join(destDir, f), 'utf8')
          .startsWith(CODEX_AGENT_HEADER);
      } catch {
        return false;
      }
    })
    .sort();
}

/**
 * Write the projection, reap header-bearing orphans, skip unchanged files.
 *
 * @param {{
 *   projectRoot: string,
 *   payloadSrc?: string,
 *   localSrc?: string,
 *   destDir?: string,
 *   log?: (line: string) => void,
 * }} opts
 * @returns {{ written: string[], removed: string[], total: number }}
 */
export function syncCodexAgents({
  projectRoot,
  payloadSrc,
  localSrc,
  destDir = path.join(projectRoot, ...CODEX_AGENTS_DIR.split('/')),
  log = () => {},
}) {
  const expected = expectedCodexAgents({ projectRoot, payloadSrc, localSrc });

  const removed = [];
  for (const file of listGeneratedCodexAgents(destDir)) {
    if (expected.has(file)) continue;
    fs.rmSync(path.join(destDir, file), { force: true });
    removed.push(file);
    log(`  removed  ${CODEX_AGENTS_DIR}/${file} (no longer in .agents/agents)`);
  }

  const written = [];
  for (const [file, body] of expected) {
    const target = path.join(destDir, file);
    let current = null;
    try {
      current = fs.readFileSync(target, 'utf8');
    } catch {
      // absent — written below
    }
    if (current === body) continue;
    if (current !== null && !current.startsWith(CODEX_AGENT_HEADER)) {
      throw new Error(
        `codex agent projection: ${CODEX_AGENTS_DIR}/${file} is hand-authored — rename it; the mandrel- prefix is reserved.`,
      );
    }
    fs.mkdirSync(destDir, { recursive: true });
    fs.writeFileSync(target, body, 'utf8');
    written.push(file);
    log(`  synced   ${CODEX_AGENTS_DIR}/${file}`);
  }
  return { written, removed, total: expected.size };
}
